@pytest.mark.parametrize("params_set", PARAMS_SETS)
@pytest.mark.parametrize("n_classes", ALL_N_CLASSES)
def test_beta_soft_labels_are_distributions(params_set, n_classes):
    """Rows are non-negative and sum to one up to the trimmed ends."""
    probs = get_beta_soft_labels(n_classes, params_set)

    assert probs.shape == (n_classes, n_classes)
    assert probs.dtype == np.float64
    assert np.isfinite(probs).all()
    assert np.all(probs >= 0.0)
    np.testing.assert_allclose(probs.sum(axis=1), 1.0, atol=1e-8)


@pytest.mark.parametrize("n_classes", ALL_N_CLASSES)
def test_beta_soft_labels_standard_are_unimodal_on_the_diagonal(n_classes):
    """Each "standard" row peaks on its own class and decreases away from it."""
    probs = get_beta_soft_labels(n_classes, "standard")

    np.testing.assert_array_equal(probs.argmax(axis=1), np.arange(n_classes))
    for j, row in enumerate(probs):
        assert np.all(np.diff(row[: j + 1]) >= -1e-12)
        assert np.all(np.diff(row[j:]) <= 1e-12)


@pytest.mark.parametrize("n_classes", ALL_N_CLASSES)
def test_beta_soft_labels_gen_are_unimodal_except_first_row(n_classes):
    """In "gen", every row but the first peaks on its own class.

    dlordinal's "gen" set gives the first class [1, J - 1, 2], whose CDF
    1 - (1 - x^2)^(J - 1) moves the peak away from class 0.
    """
    probs = get_beta_soft_labels(n_classes, "gen")

    np.testing.assert_array_equal(probs[1:].argmax(axis=1), np.arange(1, n_classes))
    for j, row in enumerate(probs[1:], start=1):
        assert np.all(np.diff(row[: j + 1]) >= -1e-12)
        assert np.all(np.diff(row[j:]) <= 1e-12)
    assert probs[0].argmax() != 0


@pytest.mark.parametrize("n_classes", ALL_N_CLASSES)
def test_beta_soft_labels_standard_are_symmetric(n_classes):
    """Class j mirrors class J - 1 - j in the "standard" set."""
    probs = get_beta_soft_labels(n_classes, "standard")

    np.testing.assert_allclose(probs, probs[::-1, ::-1], atol=1e-9)


